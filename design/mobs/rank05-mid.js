// 5격 (죽은 자의 도시) — 2칸(32) 몬스터. 5단계 입체 명암 + 손 세부, 눈 작게(1~2점), 어둑한 색, 반복 무늬 없이
const { Sprite, pair, mRect, mEll, mLine, mPoly, mTube, mLimb, noise } = require('./lib2.js');
const K = '#35263f';
const out = {};
const at = (b, list) => list.map(([x, y]) => [x, y + b]);
const mottle = (S, mat, seed, cell = 2.4, hi = 0.7, lo = 0.24) => { const nz = noise(seed, cell); S.each(mat, (x, y, t) => t + (nz(x, y) > hi ? 1 : nz(x, y) < lo ? -1 : 0)); };

// ---------- 데스 나이트 (2칸) — 대각선, 녹슨 검은 판금 · 투구 틈의 푸른 불빛 · 해진 망토 · 몸 앞에 세운 대검 ----------
function deathknight(f) {
  const b = f ? 1 : 0;
  const S = new Sprite(32).mat('a', '#4c5262', { step: 0.12 }).mat('r', '#6a4a3a').mat('c', '#3c2a34').mat('s', '#9aa2ae', { step: 0.12 }).mat('h', '#4a3a2e').color('eye', '#8ae4f8').color('void', '#0c0a12');
  // 망토 — 등 뒤, 아래 끝이 해짐 (B 는 자락이 흔들림)
  S.part('c', m => mPoly(m, f
    ? [[8, 9], [22, 9], [25, 28], [21, 26], [19, 30], [15, 27], [12, 30], [9, 27], [6, 29]]
    : [[8, 9], [22, 9], [24, 29], [20, 27], [18, 30], [14, 28], [11, 30], [8, 27], [6, 28]]), { round: 3, min: 1 });
  // 다리 — 정강이받이 (B 는 걸음)
  S.part('a', m => { mRect(m, 11, 20, 4, f ? 8 : 9); mRect(m, 17, 20, 4, 9); }, { round: 2 });
  S.part('a', m => { mRect(m, f ? 10 : 9, f ? 27 : 28, 6, 2); mRect(m, 17, 28, 6, 2); }, { round: 1, bias: -1 });
  // 몸 — 가슴판 · 허리 · 치마판
  S.part('a', m => mPoly(m, [[9, 9 + b], [22, 9 + b], [21, 17 + b], [20, 22 + b], [11, 22 + b], [10, 17 + b]]), { round: 4 });
  S.part('a', m => mPoly(m, [[10, 19 + b], [21, 19 + b], [22, 24 + b], [9, 24 + b]]), { round: 2, bias: -1 });
  // 어깨받이 — 왼쪽이 크고 각짐
  S.part('a', m => mPoly(m, [[5, 9 + b], [11, 7 + b], [12, 12 + b], [6, 13 + b]]), { round: 2 });
  S.part('a', m => mLimb(m, [[8, 12 + b, 2.2], [7, 16 + b, 1.9], [7, 19 + b, 2.1]]), { bias: -1 });
  // 대검 — 몸 앞에 세움 (끝이 땅에 닿음), 두 손이 자루를 쥠
  S.part('s', m => { mRect(m, 24, 7 + b, 2, 22 - b); mRect(m, 24, 29, 2, 1); }, { line: 'K', round: 1 });
  S.part('h', m => mRect(m, 24, 3 + b, 2, 4), { line: 'K' });
  S.part('a', m => mRect(m, 21, 6 + b, 8, 2), { line: 'K', round: 1 });
  S.part('a', m => { mLimb(m, [[21, 11 + b, 2.2], [23, 9 + b, 1.8]]); mEll(m, 24.5, 9 + b, 2, 1.8); }, { bias: -1 });
  // 투구 — 앞이 트인 틈 속은 어둠, 푸른 불빛 눈
  S.part('a', m => { mEll(m, 15.5, 5 + b, 4.2, 4.4); mRect(m, 12, 6 + b, 8, 3); }, { round: 3 });
  for (let x = 13; x <= 18; x++) S.px(x, 5 + b, 'void');
  S.pts(at(b, [[14, 6], [15, 6]]), 'void');
  S.pts(at(b, [[14, 5], [17, 5]]), 'eye');
  S.pts(at(b, [[15, 0], [16, 0], [16, 1]]), 'c2');        // 투구의 찢어진 깃
  // 녹 · 패인 자국 (자리 · 크기가 다름)
  S.pts(at(b, [[12, 12], [13, 13], [19, 15], [11, 20], [20, 22]]), 'r1');
  S.pts(at(b, [[18, 11]]), 'r2');
  S.tone(at(b, [[15, 14], [15, 15], [16, 17]]), 1);
  S.tone(at(b, [[6, 10], [7, 10], [11, 10]]), 4);
  return S.outline();
}
out.deathknight = pair(deathknight(0), deathknight(1), K, { view: '대각선' });

// ---------- 리치 (2칸) — 앞, 보랏빛 낡은 옷 · 해골 얼굴 · 이 빠진 금관 · 초록 불빛이 도는 지팡이 · 발 없이 떠 있음 ----------
function lich(f) {
  const b = f ? 1 : 0;
  const S = new Sprite(32).mat('r', '#463a5e').mat('t', '#6a5a3a').mat('o', '#c8bea4', { step: 0.12 }).mat('g', '#a48a42', { step: 0.12 }).mat('w', '#4e3e30').color('glow', '#6ae8a8').color('core', '#d8ffe8').color('void', '#0c0a12');
  // 옷 — 아래로 퍼지고 끝은 흐트러짐 (발 없음, B 는 한 점 떠오름)
  S.part('r', m => mPoly(m, [[10, 9 + b], [22, 9 + b], [25, 22 + b], [24, 27], [21, 25], [19, 29], [16, 26], [13, 29], [10, 25], [7, 27], [7, 21 + b]]), { round: 4 });
  // 옷 앞섶의 금빛 단 (한 줄, 끝이 끊김)
  for (const [x, y] of [[16, 12], [16, 13], [16, 14], [15, 16], [15, 17], [16, 19], [16, 20], [16, 21]]) S.px(x, y + b, 't2');
  // 팔 — 왼쪽은 앞으로 뼈 손을 벌림, 오른쪽은 지팡이
  S.part('r', m => mLimb(m, [[10, 11 + b, 2.6], [7, 15 + b, 2.4], [6, 17 + b, 2]]), { bias: -1 });
  S.pts(at(b, [[4, 18], [5, 19], [6, 19], [7, 19], [3, 19]]), 'o2');
  S.pts(at(b, [[3, 20], [5, 20]]), 'o1');
  // 지팡이 — 몸 앞, 손이 쥠
  S.part('w', m => mLine(m, 25, 6 + b, 26, 29, 1), { line: 'K' });
  S.part('r', m => mLimb(m, [[22, 11 + b, 2.6], [24, 14 + b, 2.2]]), { bias: -1 });
  S.pts(at(b, [[24, 15], [25, 15], [26, 15], [26, 16]]), 'o2');
  // 지팡이 끝 — 뼈 갈퀴가 감싼 초록 불빛
  S.part('o', m => { mLine(m, 23, 2 + b, 25, 6 + b, 1); mLine(m, 28, 2 + b, 26, 6 + b, 1); }, { line: 'K' });
  S.pts(at(b, [[25, 3], [26, 3], [25, 4], [26, 4]]), 'glow');
  S.pts(at(b, [[25, 3]]), 'core');
  // 머리 — 두건 속 해골
  S.part('r', m => mEll(m, 16, 6 + b, 5, 5), { round: 3 });
  S.part('o', m => mEll(m, 16, 6.5 + b, 3, 3.4), { round: 2, min: 1 });
  S.pts(at(b, [[15, 6], [17, 6]]), 'void');
  S.pts(at(b, [[15, 6], [17, 6]]), 'glow');
  S.pts(at(b, [[16, 8]]), 'void');
  for (const x of [15, 17]) S.px(x, 9 + b, 'K');
  // 이 빠진 금관 — 높이가 다른 끝
  S.pts(at(b, [[13, 3], [14, 3], [15, 3], [16, 3], [17, 3], [18, 3], [19, 3]]), 'g2');
  S.pts(at(b, [[13, 2], [15, 1], [15, 2], [18, 2], [19, 1]]), 'g3');
  S.pts(at(b, [[16, 3]]), 'g0');
  S.tone(at(b, [[12, 14], [20, 16], [13, 20], [21, 21]]), 0);
  return S.outline();
}
out.lich = pair(lich(0), lich(1), K, { view: '앞' });

// ---------- 데몬 로드 (2칸) — 대각선, 검붉은 살갗 · 굽은 두 뿔 · 작은 날개 · 검은 정장 · 손에 든 계약서 ----------
