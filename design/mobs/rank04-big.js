  S.part('i', m => mPoly(m, [[57, 3 + b], [63, 6 + b], [63, 16 + b], [57, 13 + b]]), { line: 'K', round: 2 });
  S.part('s', m => mEll(m, 53.5, 37 + b, 3.6, 3.2), { bias: -1 });
