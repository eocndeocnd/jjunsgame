  S.part('r', m => { mPoly(m, [[47, 20 + b], [55, 30 + b], [56, 40 + b], [49, 40 + b], [44, 28 + b]]); }, { round: 4, bias: -1 });
  // 지팡이 — 몸 앞, 왼 주먹이 쥠 · 끝에 푸른 보석
