out.firegiant = pair(firegiant(0), firegiant(1), K, { view: '대각선' });

// ---------- 구름 거인 (4칸) — 앞, 옅은 보랏빛 옷 · 은빛 머리 · 지팡이 · 발치에 구름 ----------
