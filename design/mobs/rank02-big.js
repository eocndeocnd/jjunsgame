  const edge = noise(31, 1.7);
  S.each('v', (x, y, t) => { const g = S.g, open = [[1, 0], [-1, 0], [0, -1]].some(([dx, dy]) => !(g[y + dy] && g[y + dy][x + dx])); return open && edge(x - sway(y), y) < 0.32 ? null : t; });
  // 나무껍질 금 — 길이 · 방향 다르게
  S.tone([[19, 19], [19, 20], [20, 21], [18, 26], [18, 27], [19, 28], [23, 30], [22, 31], [22, 32], [27, 17], [28, 18], [29, 24], [30, 25], [29, 26], [26, 33], [27, 34], [16, 33]], 1);
