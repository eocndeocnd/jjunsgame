// ---------- 바실리스크 (2칸 · 32) — 똬리를 튼 뱀 (사용자 스케치 2026-11-20): 몸이 왼쪽 아래에서 위로 크게 감아 오른쪽에서 고개를 숙여
//   머리가 고리 안으로 내려옴 · 아래에 한 겹 더 감김 · 꼬리 끝은 왼쪽 아래로. 앞을 보는 머리 · 찡그린 눈 · 갈라진 혀 · 금빛 왕관 뿔
function basilisk(f) {
  const b = f ? 1 : 0;
  const S = new Sprite(32).mat('g', '#4e6a48').mat('v', '#a89a64').mat('y', '#b08a3a', { step: 0.12 }).color('eye', '#ffe040').color('tongue', '#b03a4a');
  const tube = (m, pts, r0, r1) => { const n = pts.length; for (let i = 1; i < n; i++) { const [ax, ay] = pts[i - 1], [bx, by] = pts[i]; for (let k = 0; k <= 8; k++) { const t = k / 8, r = r0 + (r1 - r0) * ((i - 1 + t) / (n - 1)); mEll(m, ax + (bx - ax) * t, ay + (by - ay) * t, r, r); } } };
  // 꼬리 끝 (왼쪽 아래로 빠져나옴)
  S.part('g', m => tube(m, [[8, 28.5], [5, 29.5], f ? [2.5, 28.5] : [2.5, 30.5]], 1.6, 0.7), { round: 1 });
  // 아래 겹 (뒤)
  S.part('g', m => tube(m, [[7, 28], [16, 28.6], [25, 28.2], [28.5, 26.5]], 2.6, 2.6), { round: 2, min: 1 });
  // 큰 고리 — 왼쪽 아래에서 위로 감아 오른쪽 위까지
  const arc = [];
  for (let d = 125; d <= 335; d += 15) { const r = d * Math.PI / 180; arc.push([15.5 + 10 * Math.cos(r), 15 + 9.5 * Math.sin(r) + (d < 200 ? 0 : b * 0)]); }
  S.part('g', m => tube(m, arc, 3.1, 3.4), { round: 3 });
  // 배 비늘 — 고리 안쪽의 밝은 띠
  S.part('v', m => { for (let d = 140; d <= 320; d += 4) { const r = d * Math.PI / 180; mRect(m, Math.round(15.5 + 6.9 * Math.cos(r)), Math.round(15 + 6.4 * Math.sin(r)), 1, 1); } }, { line: false, cast: false, fixed: 2 });
  // 위 겹 (앞) — 고리 아래를 가로질러 오른쪽에서 말림
  S.part('g', m => tube(m, [[9, 24.5], [17, 24], [25, 24.2], [28.5, 25.5]], 2.7, 2.5), { round: 2, min: 1 });
  // 목 — 고리 오른쪽 위에서 안으로 고개를 숙임
  S.part('g', m => tube(m, [arc[arc.length - 1], [25, 11 + b], [23, 14 + b]], 3.2, 2.8), { round: 2 });
  // 머리 — 앞을 봄, 주둥이가 아래로
  S.part('g', m => { mEll(m, 21.5, 16 + b, 4.6, 3.4); mEll(m, 21.5, 18.5 + b, 3, 1.8); });
  // 왕관 뿔 — 높이가 다 다르게
  S.pts(at(b, [[20, 12], [22, 11], [22, 12], [23, 12]]), 'y3'); S.pts(at(b, [[21, 12]]), 'y1');
  // 얼굴 — 찡그린 눈썹 · 작은 눈 · 콧구멍
  S.tone(at(b, [[18, 14], [19, 15], [25, 14], [24, 15]]), 0);
  S.pts(at(b, [[19, 16], [24, 16]]), 'eye');
  S.tone(at(b, [[21, 19], [22, 19]]), 0);
  // 갈라진 혀 (B 는 넣음)
  if (!f) S.pts([[21, 21], [21, 22], [20, 23], [22, 23]], 'tongue');
  else S.pts([[21, 21 + b]], 'tongue');
  // 등 비늘 얼룩 — 몇 개만, 크기 · 자리 다르게
  S.tone([[7, 12], [8, 12], [11, 7], [19, 5], [20, 5], [21, 6], [6, 20], [14, 25], [15, 25], [24, 28]], 1);
  S.tone([[8, 9], [9, 8], [12, 6], [10, 23], [11, 23]], 4);
  return S.outline();
}
