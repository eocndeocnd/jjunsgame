  const roots = [
    [[17, 34], [12, 39], f ? [9, 42] : [8, 45]],
    [[22, 36], [21, 41], [19, 46]],
    [[27, 36], [29, 41], [31, 46]],
    [[32, 34], [37, 38], f ? [41, 45] : [40, 42]]
  ];
  roots.forEach((r, i) => S.part('w', m => mTube(m, r, 2.4, 0.6), { bias: i % 2 ? -1 : 0, round: 2 }));
  // 줄기 — 짧게, 아래가 살짝 퍼짐
  S.part('w', m => mPoly(m, [[18, 14], [30, 14], [31, 29], [34, 37], [14, 37], [17, 29]]), { round: 6 });
  // 가지 팔 — 가늘게, 잔가지는 더 가늘게. 왼쪽은 늘어뜨리고 오른쪽은 치켜듦 (좌우가 다르게)
  S.part('w', m => { mTube(m, [[18, 20], [13, 24 + b], [8, 24 + b], [4, 21 + b]], 1.7, 0.6); mTube(m, [[10, 24 + b], [8, 28 + b], [7, 31 + b]], 1, 0.5); mTube(m, [[14, 24 + b], [13, 28 + b]], 0.9, 0.5); }, { round: 1 });
