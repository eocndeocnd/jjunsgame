// 5격 (죽은 자의 도시) — 3칸(48) 네 기사 · 본 드래곤 · 발록, 4칸(64) 보스 불사의 왕. 5단계 입체 명암 + 손 세부, 눈 작게, 어둑한 색, 반복 무늬 없이
const { Sprite, pair, mRect, mEll, mLine, mPoly, mTube, mLimb, noise } = require('./lib2.js');
const K = '#35263f';
const out = {};
const at = (b, list) => list.map(([x, y]) => [x, y + b]);
const mottle = (S, mat, seed, cell = 2.6, hi = 0.7, lo = 0.22) => { const nz = noise(seed, cell); S.each(mat, (x, y, t) => t + (nz(x, y) > hi ? 1 : nz(x, y) < lo ? -1 : 0)); };

// 말 (48 칸, 옆모습 — 오른쪽을 봄). o: { lean 머리 높이(+ 면 숙임), stride 걸음 폭, gaunt 마른 말(갈빗대) }
// 다리 넷 — 앞다리 둘 · 뒷다리 둘, A · B 가 서로 엇갈림. 뒤쪽(먼) 다리를 먼저 · 어둡게
function horse(S, b, f, o = {}) {
  const lean = o.lean || 0, st = o.stride || 3, s = f ? -1 : 1;
  const leg = (x0, y0, dx, bias) => S.part('h', m => mLimb(m, [[x0, y0, 2.2], [x0 + dx * 0.5, y0 + 6, 1.5], [x0 + dx, y0 + 11, 1.2], [x0 + dx, y0 + 13, 1.4]]), { bias, round: 2 });
  leg(15, 31 + b, -st * s, -1);   // 먼 뒷다리
  leg(32, 31 + b, st * s, -1);    // 먼 앞다리
  // 꼬리 — 뒤로 늘어짐 (B 는 한 점 흔들림)
  S.part('m', m => mTube(m, [[10, 24 + b], [6, 28 + b], [5 + b, 34], [6 - b, 39]], 1.8, 0.9), { round: 1 });
  // 몸통 — 가슴이 두툼하고 배는 들어감
  S.part('h', m => mPoly(m, [[11, 22 + b], [24, 20 + b], [33, 21 + b], [36, 25 + b], [34, 31 + b], [26, 33 + b], [16, 33 + b], [10, 29 + b]]), { round: 6 });
  // 목 · 머리 — 위로 솟았다 앞으로 (lean 이면 낮게)
  S.part('h', m => { mPoly(m, [[30, 22 + b], [35, 13 + lean + b], [39, 12 + lean + b], [37, 24 + b]]); mPoly(m, [[35, 11 + lean + b], [40, 11 + lean + b], [45, 16 + lean + b], [44, 19 + lean + b], [40, 18 + lean + b], [36, 16 + lean + b]]); }, { round: 3 });
  // 귀 · 갈기
  S.pts(at(b + lean, [[36, 9], [36, 10], [37, 10]]), 'h1');
  S.part('m', m => mPoly(m, [[34, 11 + lean + b], [36, 11 + lean + b], [32, 21 + b], [29, 22 + b]]), { round: 1, cast: false });
  leg(18, 31 + b, st * s, 0);     // 가까운 뒷다리
  leg(30, 31 + b, -st * s, 0);    // 가까운 앞다리
  // 눈 · 콧구멍
  S.pts(at(b + lean, [[40, 13]]), o.eye || 'K');
  S.pts(at(b + lean, [[44, 17]]), 'K');
  // 엉덩이 · 어깨 근육 결
  S.tone(at(b, [[14, 25], [15, 24], [30, 26], [29, 27]]), 1);
  S.tone(at(b, [[19, 21], [20, 21], [12, 23]]), 4);
  if (o.gaunt) for (const [x0, y0, l] of [[19, 25, 4], [22, 24, 5], [26, 25, 3], [24, 26, 4]]) for (let k = 0; k < l; k++) S.px(x0 + (k > 2 ? 1 : 0), y0 + k + b, 'h0');   // 갈빗대 — 길이 · 자리가 다름
}
// 탄 사람 — 말 등 위 (허리 22, 20), 몸 · 머리 · 가까운 다리. 팔과 든 것은 따로
function rider(S, b, body, head) {
  S.part(body, m => { mPoly(m, [[19, 12 + b], [26, 12 + b], [27, 21 + b], [18, 21 + b]]); mLimb(m, [[23, 20 + b, 2.2], [25, 24 + b, 1.8], [25, 29 + b, 1.6]]); }, { round: 3 });
  S.part(head, m => mEll(m, 22.5, 8.5 + b, 3, 3.2), { round: 2, min: 1 });
}

// ---------- 흰 말의 기사 — 흰 말 · 금관 · 흰 옷 · 손에 든 활 (이기고 또 이기려는) ----------
function whitehorse(f) {
  const b = f ? 1 : 0;
  const S = new Sprite(48).mat('h', '#c4c0b2', { step: 0.1 }).mat('m', '#a8a498').mat('a', '#b8b09a', { step: 0.1 }).mat('s', '#b49478').mat('g', '#b0903e', { step: 0.12 }).mat('w', '#6a4e34').color('eye', '#2a2030').color('str', '#d8d0c0');
  horse(S, b, f, { stride: 3 });
  rider(S, b, 'a', 's');
  S.pts(at(b, [[23, 9]]), 'eye');
  // 금관 — 끝 높이가 다름
  S.pts(at(b, [[20, 5], [21, 5], [22, 5], [23, 5], [24, 5], [25, 5]]), 'g2');
  S.pts(at(b, [[20, 4], [22, 3], [22, 4], [25, 4]]), 'g3');
  // 활 — 앞으로 든 왼손, 휜 활대 · 시위
  S.part('w', m => { mLine(m, 32, 4 + b, 34, 9 + b, 1); mLine(m, 34, 9 + b, 34, 16 + b, 1); mLine(m, 34, 16 + b, 32, 21 + b, 1); }, { line: 'K' });
  for (let y = 5; y <= 20; y++) S.px(30, y + b, 'str');
  S.part('a', m => mLimb(m, [[25, 13 + b, 1.8], [29, 13 + b, 1.4], [33, 12 + b, 1.2]]), { bias: -1 });
  S.part('s', m => mEll(m, 33.5, 12.5 + b, 1.3, 1.3));
  // 옷자락 · 금빛 띠 하나
  S.pts(at(b, [[19, 17], [20, 17], [21, 17], [23, 17], [24, 17]]), 'g1');
  S.tone(at(b, [[20, 14], [24, 19]]), 1);
  mottle(S, 'h', 71, 3, 0.76, 0.2);
  return S.outline();
}
out.whitehorse = pair(whitehorse(0), whitehorse(1), K, { view: '옆모습' });

