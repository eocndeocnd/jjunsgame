// ---------- 본 드래곤 — 옆모습, 살 없는 뼈의 용 · 찢긴 막이 남은 날개뼈 · 갈비 틈 · 눈구멍의 초록 불 ----------
// 척추뼈 마디 — 길을 따라 하나씩 떨어진 뼈 마디 (뒤로 갈수록 작아짐). 마디 사이는 어두운 틈, 간격은 조금씩 다름 (같은 간격 반복 금지)
function vertebrae(S, pts, r0, r1, gaps, spikes = []) {
  const seg = [], len = [0];
  for (let i = 1; i < pts.length; i++) { const d = Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]); seg.push(d); len.push(len[i - 1] + d); }
  const total = len[len.length - 1], posAt = t => {
    let i = 0; while (i < seg.length - 1 && len[i + 1] < t) i++;
    const u = seg[i] ? (t - len[i]) / seg[i] : 0;
    return [pts[i][0] + (pts[i + 1][0] - pts[i][0]) * u, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * u];
  };
  // 마디 사이를 잇는 가는 등줄 (어둡게) — 마디가 공중에 뜬 것처럼 안 보이게
  S.part('o', m => mTube(m, pts, Math.max(0.6, r0 * 0.45), 0.5), { fixed: 0, line: false, cast: false });
  let t = 0, k = 0;
  while (t <= total) {
    const r = r0 + (r1 - r0) * (t / total), [x, y] = posAt(t);
    S.part('o', m => mEll(m, x, y, r * 1.15, r), { round: 1 });
    if (spikes.includes(k)) S.px(Math.round(x - 0.5), Math.round(y - r - 1), 'o3');       // 몇 마디에만 작은 가시
    t += r * 2 + gaps[k % gaps.length];
    k++;
  }
}

