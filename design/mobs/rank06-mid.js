// 6격 (마계의 왕좌) — 2칸(32) 몬스터. 5단계 입체 명암 + 손 세부, 눈 작게(1점), 어둑한 색, 반복 무늬 없이
const { Sprite, pair, mRect, mEll, mLine, mPoly, mTube, mLimb, noise } = require('./lib2.js');
const K = '#35263f';
const out = {};
const at = (b, list) => list.map(([x, y]) => [x, y + b]);
const mottle = (S, mat, seed, cell = 2.4, hi = 0.7, lo = 0.24) => { const nz = noise(seed, cell); S.each(mat, (x, y, t) => t + (nz(x, y) > hi ? 1 : nz(x, y) < lo ? -1 : 0)); };

// ---------- 아크데몬 (2칸) — 대각선, 군단을 거느린 것: 검붉은 근육질 큰 몸 · 앞으로 굽은 굵은 두 뿔 · 넓은 박쥐 날개 · 해진 군단장의 망토 · 끝이 땅에 닿는 심연의 대검 ----------
function archdemon(f) {
  const b = f ? 1 : 0, w = f ? 2 : 0;
  const S = new Sprite(32).mat('s', '#7a3a3c').mat('w', '#5c3e54').mat('v', '#2e1e2e').mat('c', '#5a2430').mat('a', '#4a4656', { step: 0.12 }).mat('n', '#b4a284', { step: 0.12 }).mat('e', '#5a5868', { step: 0.13 }).mat('h', '#24182a').mat('g', '#a46ad8', { mood: false }).color('eye', '#f4c440').color('edge', '#b47ae8');
  // 날개 — 등 뒤 양쪽, 왼쪽(가까운 쪽)이 큼 (B 는 한 점 내림)
  S.part('w', m => mPoly(m, [[11, 10 + b], [3, 0 + w], [0, 6 + w], [3, 6 + w], [1, 12 + w], [5, 11 + w], [4, 17 + w], [10, 15 + b]]), { round: 2, cast: false });
  S.part('v', m => { mLine(m, 11, 10 + b, 3, 0 + w, 1); mLine(m, 3, 0 + w, 3, 6 + w, 1); mLine(m, 3, 0 + w, 5, 11 + w, 1); }, { line: false, cast: false });
  S.part('w', m => mPoly(m, [[20, 10 + b], [27, 2 + w], [31, 7 + w], [28, 8 + w], [29, 13 + w], [24, 12 + w], [22, 15 + b]]), { round: 2, cast: false, bias: -1 });
  // 군단장의 망토 — 어깨에서 등 뒤로, 아래 끝이 들쭉날쭉 (B 는 자락이 흔들림)
  S.part('c', m => mPoly(m, f
    ? [[9, 9], [22, 9], [24, 27], [21, 25], [18, 29], [15, 26], [11, 28], [9, 25], [7, 28]]
    : [[9, 9], [22, 9], [23, 28], [20, 26], [18, 29], [14, 27], [12, 29], [9, 26], [6, 27]]), { round: 3, min: 1 });
  // 다리 — 굵은 넓적다리 · 무릎 · 발굽 (B 는 걸음)
  S.part('s', m => { mLimb(m, [[13, 20, 2.6], [12, f ? 24 : 25, 2], [12, 28, 1.8]]); mLimb(m, [[19, 20, 2.6], [20, 24, 2], [f ? 20 : 21, 28, 1.8]]); }, { round: 2 });
  S.part('h', m => { mRect(m, 10, 28, 4, 2); mRect(m, f ? 19 : 20, 28, 4, 2); }, { round: 1 });
  // 몸 — 넓은 가슴 · 잘록한 허리, 허리에 판금 띠
  S.part('s', m => mPoly(m, [[8, 9 + b], [23, 9 + b], [22, 15 + b], [20, 21 + b], [12, 21 + b], [10, 15 + b]]), { round: 4 });
  S.part('a', m => mPoly(m, [[11, 18 + b], [21, 18 + b], [22, 22 + b], [10, 22 + b]]), { round: 1 });
  S.pts(at(b, [[15, 20], [16, 20]]), 'edge');                    // 띠 가운데 보석
  // 가슴 · 배 근육 결 (자리 · 길이가 다름)
  S.tone(at(b, [[15, 11], [15, 12], [16, 13], [13, 15], [14, 15], [18, 15], [17, 16]]), 1);
  S.tone(at(b, [[11, 10], [12, 10], [13, 11], [18, 11]]), 4);
  // 어깨받이 — 왼쪽이 크고 가시 하나
  S.part('a', m => mPoly(m, [[4, 9 + b], [10, 6 + b], [12, 11 + b], [6, 13 + b]]), { round: 2 });
  S.pts(at(b, [[5, 7], [6, 7]]), 'n2');
  S.part('a', m => mPoly(m, [[20, 8 + b], [25, 8 + b], [25, 12 + b], [21, 12 + b]]), { round: 2, bias: -1 });
  // 왼팔 — 아래로 늘어뜨린 주먹
  S.part('s', m => mLimb(m, [[7, 12 + b, 2.4], [6, 16 + b, 2], [6, 19 + b, 2.2]]), { bias: -1 });
  S.pts(at(b, [[5, 21], [7, 21]]), 'n2');                         // 손톱
  // 심연의 대검 — 오른손에서 앞으로 비스듬히, 끝이 땅에 닿음 · 날 한쪽에 보랏빛
  S.part('e', m => mPoly(m, [[24, 17 + b], [27, 16 + b], [31, 29], [29, 30]]), { line: 'K', round: 1 });
  S.part('g', m => mLine(m, 27, 17 + b, 30, 27, 1), { line: false, cast: false, fixed: 2 });
  S.part('h', m => mLine(m, 22, 13 + b, 25, 16 + b, 1), { line: 'K' });
  S.part('a', m => mLine(m, 23, 17 + b, 28, 15 + b, 1), { line: 'K' });
  // 오른팔 — 칼자루를 쥠
  S.part('s', m => mLimb(m, [[22, 11 + b, 2.4], [24, 13 + b, 2]]), { bias: -1 });
  S.part('s', m => mEll(m, 24.5, 14.5 + b, 1.8, 1.7));
  // 머리 — 굵은 턱 · 송곳니
  S.part('s', m => { mEll(m, 16, 5.5 + b, 3.6, 3.6); mRect(m, 14, 7 + b, 5, 2); }, { round: 2, min: 1 });
  S.tone(at(b, [[14, 4], [15, 4], [18, 4]]), 0);                  // 굵은 눈두덩
  S.pts(at(b, [[15, 5], [18, 5]]), 'eye');
  for (const x of [15, 16, 17, 18]) S.px(x, 8 + b, 'K');
  S.pts(at(b, [[15, 9], [18, 9]]), 'n3');
  // 뿔 — 굵고 위로 솟았다 앞으로 굽음 (길이가 다름), 결 몇 줄
  S.part('n', m => { mTube(m, [[13, 3 + b], [11, 1 + b], [11, 0], [13, 0]], 1.4, 0.5); mTube(m, [[19, 3 + b], [21, 1 + b], [22, 0], [21, 0]], 1.3, 0.5); }, { line: 'K' });
  S.tone(at(b, [[12, 1], [20, 1]]), 1);
  mottle(S, 's', 113, 2.4, 0.74, 0.22);
  return S.outline();
}
out.archdemon = pair(archdemon(0), archdemon(1), K, { view: '대각선' });

// ---------- 마신장 (2칸) — 대각선, 마왕의 왼팔: 흑요석 판금(틈에서 새는 붉은 빛) · 뒤로 뻗은 두 뿔의 투구 · 겹친 어깨받이 · 붉은 앞자락 · 긴 창 ----------
function demongeneral(f) {
  const b = f ? 1 : 0;
  const S = new Sprite(32).mat('a', '#4c4262', { step: 0.13 }).mat('l', '#d0642c', { mood: false, step: 0.12 }).mat('r', '#6e2430').mat('w', '#463428').mat('e', '#9496a4', { step: 0.12 }).mat('n', '#2e2838').mat('o', '#7a5a5e', { step: 0.12 }).color('eye', '#ffb050').color('void', '#0c0a12');
  // 창 — 몸 앞 오른쪽에 세움, 끝은 머리 위로 (손이 쥠)
  S.part('w', m => mLine(m, 26, 5 + b, 26, 30, 1), { line: 'K' });
  S.part('e', m => mPoly(m, [[26, 0 + b], [28, 3 + b], [28, 5 + b], [26.9, 8.2 + b], [25.1, 8.2 + b], [24, 5 + b], [24, 3 + b]]), { line: 'K', round: 1 });
  S.part('o', m => mRect(m, 24, 8 + b, 5, 1), { line: 'K' });
  S.pts(at(b, [[29, 9], [23, 9], [23, 10]]), 'o2');                  // 날 밑 갈고리 (짧게 · 길게)
  // 다리 — 정강이받이 · 무릎 가시 (B 는 걸음)
  S.part('a', m => { mRect(m, 11, 20, 4, f ? 8 : 9); mRect(m, 17, 20, 4, 9); }, { round: 2 });
  S.part('n', m => { mRect(m, f ? 10 : 9, f ? 27 : 28, 6, 2); mRect(m, 17, 28, 6, 2); }, { round: 1 });
  S.pts([[12, 22], [18, 22]], 'a4');
  S.pts([[11, 22], [17, 21]], 'a3');
  // 붉은 앞자락 — 허리 아래로 (끝이 비스듬)
  S.part('r', m => mPoly(m, [[13, 19 + b], [19, 19 + b], [18, 26], [14, 27]]), { round: 2 });
  // 몸 — 가슴판, 판 사이 틈에서 붉은 빛
  S.part('a', m => mPoly(m, [[9, 9 + b], [22, 9 + b], [21, 16 + b], [19, 20 + b], [12, 20 + b], [10, 16 + b]]), { round: 4 });
  // 틈 — 짧은 획 몇 줄 (길이 · 기울기가 다름)
  S.pts(at(b, [[12, 14], [13, 14], [14, 15]]), 'l2');
  S.pts(at(b, [[18, 13], [18, 14], [17, 15]]), 'l1');
  S.pts(at(b, [[15, 17], [16, 17]]), 'l2');
  S.px(13, 14 + b, 'l3');
  // 어깨받이 — 두 겹, 왼쪽이 크고 끝이 뾰족
  S.part('a', m => mPoly(m, [[4, 8 + b], [11, 7 + b], [12, 12 + b], [5, 11 + b]]), { round: 2 });
  S.part('a', m => mPoly(m, [[5, 11 + b], [11, 11 + b], [11, 14 + b], [6, 13 + b]]), { round: 1, bias: -1 });
  S.pts(at(b, [[3, 7]]), 'a3');
  S.part('a', m => mEll(m, 21.5, 10 + b, 2.6, 2), { round: 2, bias: -1 });
  // 왼팔 — 건틀릿, 갈고리 손톱
  S.part('a', m => mLimb(m, [[8, 13 + b, 2], [7, 16 + b, 1.8], [7, 19 + b, 2.1]]), { bias: -1 });
  S.pts(at(b, [[6, 21], [8, 21]]), 'e3');
  S.px(7, 18 + b, 'l2');
  // 오른팔 — 창을 쥠
  S.part('a', m => mLimb(m, [[21, 12 + b, 2.2], [24, 14 + b, 1.8]]), { bias: -1 });
  S.part('a', m => mEll(m, 25.5, 14.5 + b, 1.7, 1.6));
  // 투구 — 앞이 좁은 틈, 뒤로 뻗은 두 뿔 (길이가 다름)
  S.part('o', m => { mTube(m, [[13, 4 + b], [10, 2 + b], [8, 1 + b], [7, 0]], 1.2, 0.5); mTube(m, [[18, 3 + b], [20, 1 + b], [21, 0]], 1, 0.5); }, { line: 'K' });
  S.part('a', m => { mEll(m, 15.5, 5 + b, 4, 4.2); mRect(m, 13, 6 + b, 7, 3); }, { round: 3 });
  for (let x = 15; x <= 19; x++) S.px(x, 6 + b, 'void');
  S.pts(at(b, [[16, 6], [18, 6]]), 'eye');
  S.px(17, 3 + b, 'l2');                                           // 이마의 붉은 돌
  S.tone(at(b, [[13, 3], [14, 2]]), 4);
  // 흑요석 결 · 빛 (자리 · 크기가 다름)
  S.tone(at(b, [[11, 10], [12, 10], [10, 12], [20, 17]]), 4);
  S.tone(at(b, [[19, 11], [16, 12], [20, 13]]), 0);
  return S.outline();
}
out.demongeneral = pair(demongeneral(0), demongeneral(1), K, { view: '대각선' });

module.exports = out;
