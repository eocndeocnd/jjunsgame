// 6격 (마계의 왕좌) — 3칸(48) 심연의 촉수 · 고대룡 · 종말의 짐승. 5단계 입체 명암 + 손 세부, 눈 작게, 어둑한 색, 반복 무늬 없이
const { Sprite, pair, mRect, mEll, mLine, mPoly, mTube, mLimb, noise } = require('./lib2.js');
const K = '#35263f';
const out = {};
const at = (b, list) => list.map(([x, y]) => [x, y + b]);
const mottle = (S, mat, seed, cell = 2.6, hi = 0.7, lo = 0.22) => { const nz = noise(seed, cell); S.each(mat, (x, y, t) => t + (nz(x, y) > hi ? 1 : nz(x, y) < lo ? -1 : 0)); };
const inEll = (x, y, cx, cy, rx, ry) => { const dx = (x + 0.5 - cx) / rx, dy = (y + 0.5 - cy) / ry; return dx * dx + dy * dy <= 1; };

// ---------- 심연의 촉수 — 앞, 땅에 뚫린 바닥 없는 구멍에서 굵기 · 길이가 다른 촉수 다섯이 솟음 · 안쪽 빨판 · 구멍 속 눈 둘 ----------
function abysstentacle(f) {
  const S = new Sprite(48).mat('t', '#5c4876', { step: 0.12 }).mat('u', '#b27a8e', { step: 0.1 }).mat('p', '#2e2a3a').color('void', '#08060c').color('eye', '#d8ec70');
  const sw = f ? 1 : 0;
  // 구멍 — 바깥 테두리(갈라진 땅) · 속은 어둠
  S.part('p', m => { for (let y = 34; y < 48; y++) for (let x = 0; x < 48; x++) if (inEll(x, y, 24, 41.5, 18, 5.6)) m[y][x] = true; }, { round: 2, cast: false });
  S.part('p', m => { mPoly(m, [[5, 40], [2, 42], [6, 43]]); mPoly(m, [[41, 39], [46, 40], [42, 42]]); }, { round: 1, cast: false, bias: -1 });   // 갈라진 끝 (길이가 다름)
  for (let y = 34; y < 48; y++) for (let x = 0; x < 48; x++) if (inEll(x, y, 24, 41, 15.5, 4.2)) S.px(x, y, 'void');
  // 먼 촉수 둘 — 작고 어둡게
  S.part('t', m => mTube(m, [[11, 41], [7, 37], [5, 33 - sw], [6, 30 - sw], [8, 30]], 1.9, 0.5), { bias: -1, round: 2 });
  S.part('t', m => mTube(m, [[37, 41], [41, 38], [44, 34 + sw], [44, 31 + sw], [42, 30 + sw]], 1.7, 0.5), { bias: -1, round: 2 });
  // 옆 촉수 둘 — 바깥으로 휘었다 끝이 안으로 말림 (B 는 서로 반대로 흔들림)
  S.part('t', m => mTube(m, [[17, 41], [13, 35], [10, 29], [10 - sw, 23], [12 - sw, 19], [15 - sw, 19], [15, 21]], 3.1, 0.6), { round: 3 });
  S.part('t', m => mTube(m, [[31, 41], [35, 35], [39, 30], [41 + sw, 25], [41 + sw, 21], [39 + sw, 20]], 2.9, 0.6), { round: 3 });
  // 가운데 큰 촉수 — 가장 굵고 높이 솟아 끝이 말림
  S.part('t', m => mTube(m, [[24, 42], [22, 34], [23, 26], [26 + sw, 18], [30 + sw, 12], [30 + sw, 6], [27 + sw, 3], [25 + sw, 5], [26 + sw, 7]], 4.4, 0.6), { round: 4 });
  // 빨판 — 촉수 안쪽에만, 크기 · 간격이 다름 (바깥 줄은 어둑, 가운데는 밝게)
  const sucker = (x, y, r) => { S.part('u', m => mEll(m, x, y, r, r * 0.85), { fixed: r > 0.95 ? 3 : 2, line: false, cast: false }); S.px(Math.floor(x), Math.floor(y), 'u0'); };
  for (const [x, y, r] of [[20, 35, 1.3], [20.5, 30, 1.1], [22, 25, 1], [25, 19.5, 0.8], [28.5, 13, 0.75]]) sucker(x + (y < 22 ? sw : 0), y, r);
  for (const [x, y, r] of [[14.5, 34, 1], [12.5, 28, 0.9], [13 - sw, 23.5, 0.7]]) sucker(x, y, r);
  for (const [x, y, r] of [[33, 35, 1], [36.5, 30, 0.85], [38.5 + sw, 25, 0.7]]) sucker(x, y, r);
  // 구멍 앞 테두리 — 촉수 밑동을 덮음
  S.part('p', m => { for (let y = 38; y < 48; y++) for (let x = 0; x < 48; x++) if (inEll(x, y, 24, 41.5, 18, 5.6) && !inEll(x, y, 24, 40.2, 16, 4.6)) m[y][x] = true; }, { round: 1, cast: false });
  // 구멍 속 눈 둘 (높이가 다름, B 는 하나가 감김)
  S.px(18, 43, 'eye');
  if (!f) S.px(30, 42, 'eye');
  // 촉수 결 — 등 쪽 빛 · 주름 (자리가 다름)
  S.tone([[24, 29], [25, 24], [27 + sw, 17], [29 + sw, 9]], 4);
  S.tone([[11, 30], [12, 25], [36, 34], [40 + sw, 27]], 3);
  mottle(S, 't', 131, 2.4, 0.76, 0.2);
  return S.outline();
}
out.abysstentacle = pair(abysstentacle(0), abysstentacle(1), K, { view: '앞' });

// ---------- 고대룡 — 옆모습, 신화보다 오래된 비늘: 이끼 낀 듯 바랜 청동빛 큰 몸 · 반쯤 든 날개 · 뒤로 휜 굵은 뿔 · 턱밑 가시 수염 · 등 가시 · 배 비늘판 ----------
function elderdragon(f) {
  const b = f ? 1 : 0, w = f ? 2 : 0;
  const S = new Sprite(48).mat('d', '#56664a').mat('y', '#a8946a', { step: 0.1 }).mat('w', '#6e4c42').mat('v', '#a89070', { step: 0.1 }).mat('n', '#b0a080', { step: 0.12 }).color('eye', '#f0a830').color('claw', '#d8ccb0');
  // 먼 날개 — 등 뒤로 솟음 (B 는 내림)
  S.part('w', m => mPoly(m, [[28, 22 + b], [25, 4 + w], [21, 4 + w], [23, 9 + w], [20, 11 + w], [23, 21 + b]]), { round: 2, cast: false, bias: -1 });
  S.part('v', m => mLine(m, 28, 22 + b, 25, 4 + w, 1), { line: false, cast: false, bias: -1 });
  // 먼 다리 둘 — 어둡게 (B 는 걸음)
  const leg = (pts, claws, bias) => { S.part('d', m => mLimb(m, pts), { round: 2, bias }); S.pts(claws, 'claw'); };
  leg([[16, 30 + b, 3], [14, 36, 2.4], [15, 40, 1.8], [14, 42, 2]], f ? [[16, 44], [18, 44]] : [[15, 44], [17, 44]], -1);
  leg([[32, 30 + b, 2.8], [34, 36, 2.2], [33, 41, 1.8], [33, 42, 2]], f ? [[36, 44]] : [[35, 44], [37, 44]], -1);
  // 꼬리 — 굵게 시작해 뒤로 낮게 휨, 끝은 납작한 가시
  S.part('d', m => mTube(m, [[14, 28 + b], [8, 30 + b], [4, 34], [3, 39], [6, 43]], 4, 0.8), { round: 3 });
  S.part('n', m => mPoly(m, [[5, 42], [9, 42], [8, 45], [6, 46]]), { round: 1, line: 'K' });
  // 몸
  S.part('d', m => mEll(m, 23, 29 + b, 11.5, 6.8), { round: 6 });
  // 배 비늘판 — 아래쪽, 판 사이 틈은 간격이 다름
  S.part('y', m => mPoly(m, [[13, 32 + b], [32, 32 + b], [30, 35 + b], [16, 35 + b]]), { round: 1 });
  for (const x of [17, 21, 24, 28]) S.pts([[x, 33 + b], [x, 34 + b]], 'y0');
  // 목 — 앞으로 솟아 머리로, 아래쪽 비늘판
  S.part('d', m => mTube(m, [[31, 27 + b], [35, 21 + b], [37, 16 + b], [39, 12 + b]], 4.6, 2.8), { round: 3 });
  S.part('y', m => mTube(m, [[34, 27 + b], [38, 21 + b], [40, 16 + b]], 1.4, 1), { round: 1, cast: false });
  // 머리 — 긴 주둥이 · 다문 턱
  S.part('d', m => mPoly(m, [[36, 8 + b], [42, 8 + b], [47, 11 + b], [47, 14 + b], [44, 16 + b], [38, 16 + b], [35, 13 + b]]), { round: 2 });
  for (let x = 40; x <= 46; x++) S.px(x, 14 + b, x === 44 ? 'claw' : 'K');                 // 다문 입 · 삐져나온 이 하나
  S.tone(at(b, [[39, 10], [40, 10], [41, 10]]), 0);                                          // 굵은 눈두덩
  S.px(40, 11 + b, 'eye');
  S.px(46, 12 + b, 'K');                                                                    // 콧구멍
  S.tone(at(b, [[42, 9], [43, 9], [45, 10]]), 4);
  // 뿔 — 굵고 뒤로 휨 (위 · 아래 길이가 다름), 결 몇 줄
  S.part('n', m => mTube(m, [[38, 9 + b], [35, 7 + b], [32, 6 + b], [30, 7 + b], [29, 9 + b]], 1.6, 0.5), { line: 'K', round: 1 });
  S.part('n', m => mTube(m, [[37, 12 + b], [34, 11 + b], [32, 13 + b]], 1.2, 0.5), { line: 'K', round: 1, bias: -1 });
  S.tone(at(b, [[34, 7], [32, 6]]), 1);
  // 턱밑 가시 수염 — 길이가 다름
  S.pts(at(b, [[39, 17], [40, 18], [42, 17], [41, 17], [43, 17]]), 'n1');
  S.pts(at(b, [[40, 19]]), 'n0');
  // 등 가시 — 목에서 꼬리까지, 크기 · 간격이 다름
  for (const [x, y, h] of [[36, 15, 2], [33, 20, 2], [29, 22, 3], [24, 22, 2], [20, 23, 3], [15, 24, 2], [10, 27, 1]]) S.part('n', m => mPoly(m, [[x - 1, y + b], [x + 1, y + b], [x - 0.5, y - h + b]]), { round: 1, bias: -1, cast: false });
  // 가까운 다리 둘 — 뒷다리는 굵은 넓적다리, 앞다리는 굵은 팔
  leg([[18, 29 + b, 4.4], [15, 35, 3.2], [17, 40, 2.2], [16, 42, 2.4]], f ? [[18, 44], [19, 43]] : [[17, 44], [19, 44]], 0);
  leg([[30, 30 + b, 3.4], [32, 36, 2.6], [31, 40, 2], [32, 42, 2.4]], f ? [[33, 44], [35, 44]] : [[34, 44], [35, 43]], 0);
  // 가까운 날개 — 반쯤 들어 올림, 뼈 손가락 셋 사이 막 · 찢긴 자리 하나 (B 는 내림)
  const T = f ? [[22, 6 + w], [9, 6 + w], [6, 13 + w], [12, 19 + w]] : [[23, 2], [9, 3], [5, 10], [10, 17]];
  S.part('w', m => mPoly(m, [[28, 23 + b], T[0], T[1], [12, 9 + w], T[2], [13, 15 + w], T[3], [21, 22 + b]]), { round: 2, min: 1, max: 3 });
  S.part('v', m => { mLine(m, 28, 23 + b, T[0][0], T[0][1], 1); mLine(m, T[0][0], T[0][1], T[1][0], T[1][1], 1); mLine(m, T[0][0], T[0][1], T[2][0], T[2][1], 1); mLine(m, T[0][0], T[0][1], T[3][0], T[3][1], 1); }, { line: false, cast: false, fixed: 2 });
  S.pts([T[0], [T[0][0] - 1, T[0][1]]], 'n2');                                               // 날개 끝 발톱
  S.clear(f ? [[11, 11], [12, 12]] : [[10, 8], [11, 9]]);                                      // 막의 찢긴 구멍
  // 오래된 상처 · 바랜 비늘 (자리 · 길이가 다름)
  S.tone(at(b, [[22, 26], [23, 27], [24, 27], [27, 30]]), 0);
  mottle(S, 'd', 137, 2.2, 0.74, 0.24);
  return S.outline();
}
out.elderdragon = pair(elderdragon(0), elderdragon(1), K, { view: '옆모습' });

// ---------- 종말의 짐승 — 옆모습, 뿔이 일곱 개인: 어깨가 솟은 큰 검붉은 짐승 · 낮게 숙인 머리에서 사방으로 뻗은 일곱 뿔(길이 · 휨이 다 다름) · 어깨를 덮은 거친 갈기 · 짓밟는 쇠 각반 ----------
function apocalypsebeast(f) {
  const b = f ? 1 : 0, st = f ? -2 : 2;
  const S = new Sprite(48).mat('h', '#5a3034').mat('g', '#6e3e3a').mat('f', '#3a2a38').mat('n', '#a8987a', { step: 0.12 }).mat('i', '#6c6a78', { step: 0.12 }).mat('k', '#2a2028').color('eye', '#ff6040');
  // 꼬리 — 엉덩이에서 늘어짐, 끝에 털 뭉치 (B 는 흔들림)
  S.part('h', m => mTube(m, [[9, 21 + b], [5, 24 + b], [3 + b, 30]], 1, 0.6), { round: 1 });
  S.part('f', m => mEll(m, 3.5 + b, 31.5, 1.8, 2.6), { round: 1 });
  // 다리 — 굵은 기둥, 쇠 각반 · 발굽. 먼 다리 먼저 어둡게 (B 는 걸음)
  const leg = (x, dx, bias, band) => {
    S.part('h', m => mLimb(m, [[x, 29 + b, 3.4], [x + dx * 0.5, 36, 2.6], [x + dx, 41, 2.4]]), { round: 2, bias });
    S.part('i', m => mRect(m, Math.round(x + dx * 0.6) - 2, band, 5, 3), { round: 1, bias });
    S.part('k', m => mRect(m, Math.round(x + dx) - 2, 42, 5, 2), { round: 1, bias });
  };
  leg(13, st, -1, 36);
  leg(33, -st, -1, 35);
  // 몸 — 어깨가 높이 솟고 엉덩이로 낮아짐
  S.part('h', m => mPoly(m, [[8, 21 + b], [16, 17 + b], [25, 11 + b], [33, 11 + b], [38, 16 + b], [38, 26 + b], [34, 33 + b], [14, 33 + b], [8, 28 + b]]), { round: 7 });
  // 갈빗대 · 근육 결 (길이 · 자리가 다름)
  S.tone(at(b, [[19, 25], [20, 26], [20, 27], [23, 26], [24, 27], [24, 28], [25, 29]]), 1);
  S.tone(at(b, [[14, 20], [15, 19], [26, 14], [27, 14]]), 4);
  // 갈기 — 어깨 · 목을 덮음, 아래 끝이 들쭉날쭉 (뾰족한 끝 길이가 다름)
  S.part('f', m => mPoly(m, [[21, 15 + b], [27, 9 + b], [34, 9 + b], [39, 13 + b], [40, 22 + b], [38, 27 + b], [36, 24 + b], [35, 28 + b], [33, 23 + b], [30, 25 + b], [29, 20 + b], [26, 22 + b], [25, 18 + b], [22, 19 + b]]), { round: 3 });
  mottle(S, 'f', 149, 1.8, 0.7, 0.28);
  // 가까운 다리
  leg(16, -st, 0, 37);
  leg(30, st, 0, 35);
  // 머리 — 낮게 앞으로 숙임, 두툼한 주둥이
  S.part('g', m => mPoly(m, [[37, 18 + b], [43, 19 + b], [47, 24 + b], [46, 29 + b], [42, 31 + b], [38, 28 + b], [36, 23 + b]]), { round: 3, min: 1 });
  S.tone(at(b, [[44, 27], [45, 27], [43, 28], [44, 28]]), 1);
  S.tone(at(b, [[42, 20], [43, 21], [44, 22]]), 4);
  S.px(46, 26 + b, 'K');                                                                    // 콧구멍
  for (const x of [42, 43, 44, 45]) S.px(x, 29 + b, 'K');                                  // 입
  S.tone(at(b, [[40, 21], [41, 21]]), 0);
  S.px(41, 22 + b, 'eye');
  // 일곱 뿔 — 굵기 · 길이 · 휨이 다 다름 (뒤로 감긴 큰 뿔 · 앞 가시 · 위로 · 뒤로 길게 · 작은 것 · 아래로 말린 것 · 앞위로)
  const horns = [
    [[[41, 18], [39, 13], [36, 11], [34, 13]], 1.8, 0.6, -1],             // 먼 쪽 큰 뿔 — 뒤로 감김
    [[[39, 17], [35, 12], [33, 7], [34, 4]], 1.3, 0.4, -1],               // 뒤로 길게 휘어 끝이 위로
    [[[41, 17], [42, 12], [41, 8], [39, 6]], 1.4, 0.4, 0],                // 위로 솟아 뒤로 굽음
    [[[43, 19], [46, 16], [47, 12], [46, 10]], 1.4, 0.4, 0],              // 앞으로 뻗어 위로
    [[[43, 18], [45, 14]], 1, 0.4, 0],                                    // 작은 것
    [[[45, 21], [47, 22]], 0.9, 0.5, 0],                                  // 주둥이 위 짧은 가시
    [[[40, 19], [37, 15], [34, 16], [33, 20], [34, 24], [37, 26]], 1.7, 0.6, 0]   // 가까운 쪽 큰 뿔 — 귀를 감아 앞으로 말림
  ];
  for (const [pts, r0, r1, bias] of horns) S.part('n', m => mTube(m, pts.map(([x, y]) => [x, y + b]), r0, r1), { line: 'K', round: 1, bias });
  S.tone(at(b, [[36, 17], [35, 20], [37, 12], [34, 9], [42, 11], [46, 14]]), 1);                      // 뿔 결
  mottle(S, 'h', 151, 2.6, 0.76, 0.22);
  return S.outline();
}
out.apocalypsebeast = pair(apocalypsebeast(0), apocalypsebeast(1), K, { view: '옆모습' });

module.exports = out;
