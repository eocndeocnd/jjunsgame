  S.pts(at(b, [[22, 16], [23, 17], [24, 17], [30, 16], [31, 17], [32, 18]]), 'h0');   // 눈가에서 늘어진 짙은 줄
  // 눈 — 무거운 눈꺼풀 (A 는 반쯤 뜸, B 는 감음)
  S.pts(at(b, [[24, 16], [25, 16], [29, 16], [30, 16]]), 'K');
  if (!f) S.pts([[25, 17], [29, 17]], 'eye'); else S.pts([[25, 18], [29, 18]], 's1');
  S.px(27, 19 + b, 'K');                                                           // 코
  S.pts(at(b, [[26, 21], [27, 21], [28, 21]]), 's0');                              // 늘어진 입
  S.px(28, 22 + b, 's0');
