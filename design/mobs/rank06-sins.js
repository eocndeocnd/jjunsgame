// 6격 칠죄종 (정예 일곱) — 질투 · 색욕 2칸(32), 나태 · 오만 · 분노 · 탐욕 3칸(48), 폭식 4칸(64). 5단계 입체 명암 + 손 세부, 눈 작게, 어둑한 색, 반복 무늬 없이
const { Sprite, pair, mRect, mEll, mLine, mPoly, mTube, mLimb, noise } = require('./lib2.js');
const K = '#35263f';
const out = {};
const at = (b, list) => list.map(([x, y]) => [x, y + b]);
const mottle = (S, mat, seed, cell = 2.4, hi = 0.7, lo = 0.24) => { const nz = noise(seed, cell); S.each(mat, (x, y, t) => t + (nz(x, y) > hi ? 1 : nz(x, y) < lo ? -1 : 0)); };

// ---------- 질투 (2칸) — 대각선, 남의 것이 더 좋아 보이는: 웅크린 마른 초록 몸 · 여기저기서 뜯어 기운 망토 · 앞으로 뻗은 긴 팔에 훔쳐 낀 금단 장갑 ----------
function sinenvy(f) {
  const b = f ? 1 : 0, r = f ? 1 : 0;
  const S = new Sprite(32).mat('s', '#6e8a5c').mat('p', '#5e3e5e').mat('q', '#3e4e6e').mat('u', '#6e5234').mat('g', '#8a6440').mat('o', '#b0903e', { step: 0.12 }).color('eye', '#b4f064');
  // 다리 — 가늘고 굽음 (B 는 걸음)
  S.part('s', m => { mLimb(m, [[12, 23, 1.4], [10, f ? 26 : 27, 1], [11, 29, 1.1]]); mLimb(m, [[17, 23, 1.4], [19, 26, 1], [f ? 19 : 20, 29, 1.1]]); }, { round: 1, bias: -1 });
  // 기운 망토 — 웅크린 등 (조각마다 다른 천, 이은 자리는 어두운 선)
  S.part('p', m => mPoly(m, [[7, 11 + b], [14, 7 + b], [20, 8 + b], [22, 14 + b], [21, 22 + b], [18, 26], [13, 25], [9, 27], [6, 21 + b]]), { round: 4 });
  S.part('q', m => mPoly(m, [[7, 17 + b], [13, 16 + b], [14, 22 + b], [13, 25], [9, 27], [6, 21 + b]]), { round: 2 });
  S.part('u', m => mPoly(m, [[15, 9 + b], [19, 8 + b], [21, 12 + b], [16, 13 + b]]), { round: 1 });
  S.pts(at(b, [[11, 14], [12, 13], [17, 18], [18, 19]]), 'p1');                     // 해진 자리 몇 군데 (크기가 다름)
  // 웅크린 쪽 팔 — 망토 앞섶을 움켜쥠
  S.part('s', m => mLimb(m, [[14, 13 + b, 1.3], [15, 17 + b, 1], [17, 18 + b, 1.1]]), { bias: -1, round: 1 });
  // 두건 · 앞으로 내민 얼굴
  S.part('p', m => mPoly(m, [[14, 5 + b], [20, 3 + b], [24, 6 + b], [24, 10 + b], [19, 11 + b], [15, 9 + b]]), { round: 2 });
  S.part('s', m => mPoly(m, [[20, 6 + b], [24, 7 + b], [25, 9 + b], [23, 11 + b], [20, 10 + b]]), { round: 1, min: 1 });
  S.px(23, 8 + b, 'eye');
  S.tone(at(b, [[21, 7], [22, 7]]), 0);
  S.pts(at(b, [[22, 10], [23, 10]]), 'K');
  // 뻗은 팔 — 길고 가늘게, 손에 금단 두른 장갑 (B 는 더 뻗음)
  S.part('s', m => mLimb(m, [[19, 13 + b, 1.4], [24, 14 + b, 1.1], [27 + r, 13, 1]]), { round: 1 });
  S.part('g', m => mEll(m, 28.5 + r, 12.5, 1.8, 1.6), { round: 1 });
  S.pts([[26 + r, 12], [26 + r, 13], [26 + r, 14]], 'o2');
  S.pts([[30 + r, 11], [31, 13 - r], [30 + r, 14]], 'g1');                            // 갈고리처럼 오므린 손가락
  mottle(S, 'p', 161, 2.2, 0.76, 0.22);
  return S.outline();
}
out.sinenvy = pair(sinenvy(0), sinenvy(1), K, { view: '대각선' });

// ---------- 색욕 (2칸) — 앞, 눈을 떼지 못하게 하는: 길게 끌리는 비단 망토 · 웃는 사기 가면 · 내민 손 위에 빛나는 반지 ----------
