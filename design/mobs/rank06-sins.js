// ---------- 오만 (3칸) — 앞, 무릎 꿇는 법을 모르는: 곧게 선 상아빛 갑주 · 높은 오만의 관 · 치켜든 턱 · 곧게 드리운 보라 망토 · 손거울을 들어 제 얼굴을 봄 ----------
