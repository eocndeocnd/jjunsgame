  S.part('f', m => mEll(m, 24.5, 32 + b * 0.5, 14, 12 - b * 0.5), { round: 9 });
  S.part('s', m => mEll(m, 25, 35 + b * 0.5, 7.4, 6.6), { round: 4, cast: false });
  mottle(S, 'f', 171, 2, 0.72, 0.26);
