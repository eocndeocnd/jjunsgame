  S.part('f', m => mLimb(m, [[13, 24 + b, 3.6], [10, 31 + b, 3], [9, 38, 2.5], [9, 43, 2.4]]), { round: 2 });
  S.part('f', m => mLimb(m, [[36, 24 + b, 3.6], [40, 31 + b, 3], [41, 38, 2.5], [41, 43, 2.4]]), { round: 2 });
  for (const [x0, y0, x1, y1] of [[7, 44, 5, 47], [9, 45, 8, 47], [11, 44, 12, 47], [39, 45, 38, 47], [41, 45, 42, 47], [43, 44, 45, 46]]) S.part('n', m => mLine(m, x0, y0, x1, y1, 1), { line: false, cast: false, fixed: 2 });
  // 머리 — 어깨에 묻혀 오른쪽으로 기움, 얼굴은 밝은 털 · 눈가는 짙은 줄
  S.part('h', m => mEll(m, 26, 17 + b, 8, 7), { round: 5 });
